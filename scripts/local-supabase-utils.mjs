export function parseSupabaseStatus(output) {
  const values = Object.fromEntries(
    output.split(/\r?\n/).flatMap((line) => {
      const match = line.match(/^([A-Z_]+)=(.*)$/);
      if (!match) return [];
      const value = match[2].trim().replace(/^(?:"(.*)"|'(.*)')$/, (_, double, single) => double ?? single);
      return [[match[1], value]];
    }),
  );

  if (!values.API_URL || !values.ANON_KEY || !values.SERVICE_ROLE_KEY) {
    throw new Error('Supabase CLI status output did not include API_URL, ANON_KEY, and SERVICE_ROLE_KEY.');
  }

  return {
    apiUrl: values.API_URL,
    anonKey: values.ANON_KEY,
    serviceRoleKey: values.SERVICE_ROLE_KEY,
  };
}

export function renderLocalEnv({ apiUrl, anonKey, serviceRoleKey }) {
  let parsedUrl;
  try {
    parsedUrl = new URL(apiUrl);
  } catch {
    throw new Error('Refusing to write env settings: invalid local Supabase URL.');
  }
  if (!['localhost', '127.0.0.1', '::1'].includes(parsedUrl.hostname)) {
    throw new Error('Refusing to write env settings: expected a local Supabase URL.');
  }
  if (!anonKey || !serviceRoleKey) throw new Error('Local Supabase keys are missing.');

  return [
    '# Generated by scripts/local-dev-setup.mjs from the local Supabase CLI.',
    '# This ignored file overrides .env.local for local Next.js and Python development.',
    `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
    `SUPABASE_URL=${apiUrl}`,
    `SUPABASE_ANON_KEY=${anonKey}`,
    `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}`,
    'NEXT_PUBLIC_SITE_URL=http://localhost:3000',
    'NEXT_PUBLIC_BACKEND_API_URL=http://localhost:8000',
    'BACKEND_CORS_ORIGINS=["http://localhost:3000","http://127.0.0.1:3000"]',
    '',
  ].join('\n');
}
